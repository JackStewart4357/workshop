
BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email         TEXT NOT NULL UNIQUE CHECK (email = lower(email) AND email LIKE '%_@acme.inc'),
    full_name     TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('EMPLOYEE', 'ENGINEER', 'ADMIN')),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,                         -- bumped on logout to revoke tokens
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Holds the JWT signing key generated by the auth service.
CREATE TABLE IF NOT EXISTS app_secrets (
    name  TEXT PRIMARY KEY,
    value TEXT NOT NULL
);


CREATE TABLE IF NOT EXISTS engineer_profiles (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id          UUID NOT NULL UNIQUE REFERENCES users (id),
    specialism       TEXT NOT NULL,
    is_available     BOOLEAN NOT NULL DEFAULT TRUE,
    max_open_tickets INTEGER NOT NULL DEFAULT 5 CHECK (max_open_tickets > 0),
    manager_id       UUID REFERENCES users (id),          -- the admin who alone may read this engineer's feedback
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- For databases created before the manager column existed.
ALTER TABLE engineer_profiles ADD COLUMN IF NOT EXISTS manager_id UUID REFERENCES users (id);

CREATE TABLE IF NOT EXISTS buildings (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name       TEXT NOT NULL UNIQUE,
    address    TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS floors (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    building_id UUID NOT NULL REFERENCES buildings (id),
    level       INTEGER NOT NULL,                       -- 0 = ground, negative = basement
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (building_id, level),
    UNIQUE (id, building_id)                            -- target for the incidents location check
);

CREATE TABLE IF NOT EXISTS seats (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    floor_id   UUID NOT NULL REFERENCES floors (id),
    code       TEXT NOT NULL,                           -- e.g. 2F-A14
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (floor_id, code),
    UNIQUE (id, floor_id)                               -- target for the incidents location check
);

CREATE TABLE IF NOT EXISTS categories (
    id   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL UNIQUE,
    type TEXT NOT NULL CHECK (type IN ('FACILITY', 'TECHNOLOGY'))
);

CREATE TABLE IF NOT EXISTS incidents (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title             TEXT NOT NULL,
    description       TEXT NOT NULL,
    status            TEXT NOT NULL DEFAULT 'OPEN'
                      CHECK (status IN ('OPEN', 'IN_PROGRESS', 'BLOCKED', 'RESOLVED', 'CLOSED')),
    priority          TEXT NOT NULL DEFAULT 'MEDIUM'
                      CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    category_id       UUID NOT NULL REFERENCES categories (id),

    -- Location: building is required, floor and seat are optional.
    building_id       UUID NOT NULL REFERENCES buildings (id),
    floor_id          UUID,
    seat_id           UUID,

    reporter_id       UUID NOT NULL REFERENCES users (id),
    assignee_id       UUID REFERENCES engineer_profiles (id),

    is_escalated      BOOLEAN NOT NULL DEFAULT FALSE,
    escalation_reason TEXT,
    escalated_by      UUID REFERENCES users (id),
    escalated_at      TIMESTAMPTZ,
    blocked_reason    TEXT,
    duplicate_of      UUID REFERENCES incidents (id) ON DELETE SET NULL,

    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    acknowledged_at   TIMESTAMPTZ,                      -- first staff action on the incident
    assigned_at       TIMESTAMPTZ,                      -- latest assignment
    resolved_at       TIMESTAMPTZ,                      -- latest resolution (history keeps earlier ones)
    closed_at         TIMESTAMPTZ,

    -- The floor must be in the chosen building and the seat on the chosen floor.
    CONSTRAINT incidents_floor_in_building FOREIGN KEY (floor_id, building_id)
        REFERENCES floors (id, building_id),
    CONSTRAINT incidents_seat_on_floor FOREIGN KEY (seat_id, floor_id)
        REFERENCES seats (id, floor_id),
    CONSTRAINT incidents_seat_needs_floor CHECK (seat_id IS NULL OR floor_id IS NOT NULL),

    CONSTRAINT incidents_blocked_has_reason
        CHECK (status <> 'BLOCKED' OR btrim(coalesce(blocked_reason, '')) <> ''),
    CONSTRAINT incidents_escalation_complete
        CHECK (NOT is_escalated
               OR (btrim(coalesce(escalation_reason, '')) <> ''
                   AND escalated_by IS NOT NULL AND escalated_at IS NOT NULL)),
    CONSTRAINT incidents_not_own_duplicate CHECK (duplicate_of IS NULL OR duplicate_of <> id)
);

CREATE INDEX IF NOT EXISTS incidents_reporter_idx    ON incidents (reporter_id);
CREATE INDEX IF NOT EXISTS incidents_assignee_idx    ON incidents (assignee_id);
CREATE INDEX IF NOT EXISTS incidents_location_idx    ON incidents (building_id, floor_id, seat_id);
CREATE INDEX IF NOT EXISTS incidents_created_at_idx  ON incidents (created_at DESC);


CREATE TABLE IF NOT EXISTS incident_notes (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id UUID NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    author_id   UUID NOT NULL REFERENCES users (id),
    body        TEXT NOT NULL CHECK (btrim(body) <> ''),
    is_internal BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS incident_notes_incident_idx ON incident_notes (incident_id, created_at);


CREATE TABLE IF NOT EXISTS incident_status_history (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id UUID NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    from_status TEXT CHECK (from_status IN ('OPEN', 'IN_PROGRESS', 'BLOCKED', 'RESOLVED', 'CLOSED')),
    to_status   TEXT NOT NULL CHECK (to_status IN ('OPEN', 'IN_PROGRESS', 'BLOCKED', 'RESOLVED', 'CLOSED')),
    changed_by  UUID NOT NULL REFERENCES users (id),
    reason      TEXT,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS incident_status_history_incident_idx
    ON incident_status_history (incident_id, changed_at);


CREATE TABLE IF NOT EXISTS ai_suggestions (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id        UUID NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    type               TEXT NOT NULL CHECK (type IN ('TRIAGE', 'DUPLICATE', 'FIX')),
    suggestion         JSONB NOT NULL,
    applied            JSONB,
    cited_incident_ids UUID[] NOT NULL DEFAULT '{}',
    decision           TEXT NOT NULL DEFAULT 'PENDING'
                       CHECK (decision IN ('PENDING', 'APPROVED', 'EDITED', 'REJECTED')),
    decided_by         UUID REFERENCES users (id),
    decided_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Pending means nobody has decided; any other decision records who and when.
    CONSTRAINT ai_suggestions_decision_complete
        CHECK ((decision = 'PENDING') = (decided_by IS NULL AND decided_at IS NULL)),
    CONSTRAINT ai_suggestions_decided_together
        CHECK ((decided_by IS NULL) = (decided_at IS NULL))
);

CREATE INDEX IF NOT EXISTS ai_suggestions_incident_idx ON ai_suggestions (incident_id);

