    ('Access & Security',  'FACILITY'),
    ('Network',            'TECHNOLOGY'),
    ('Hardware',           'TECHNOLOGY'),
    ('Software',           'TECHNOLOGY'),
    ('Audio / Video',      'TECHNOLOGY')
ON CONFLICT (name) DO NOTHING;

COMMIT;
